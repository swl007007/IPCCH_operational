"""Regenerate cloud/ipcch/vendor/seasonal_spi_spei_v3.py: the verbatim source of the seasonal SPI/SPEI functions of the
shared-folder ``seasonal/spi&spei.py`` (sha256 pinned), extracted by AST (task 10-29 R1/R34/R40). The vendored text keeps
the original functions byte for byte; their module globals are bound explicitly by ``cloud.ipcch.spi_spei_seasonal``.

  python tools/vendor_ipcch_seasonal_spi_spei.py "<IPCCH_shared_folder>/seasonal/spi&spei.py"
"""
import ast
import hashlib
import os
import sys

SHA = "fbc559792896f5dc251aceb1ad83926c0cbdf2107c713aeb14701359dea690a7"
FUNCTIONS = ("rolling_three_month_sum", "normal_from_probability", "compute_spi03", "fit_glo_ubpwm", "glo_probability_strict",
             "compute_spei03", "truthy", "int_or_none", "exact_date", "aggregate_gs", "add_ensemble")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "cloud", "ipcch", "vendor", "seasonal_spi_spei_v3.py")


def extract(path):
    raw = open(path, "rb").read()
    if hashlib.sha256(raw).hexdigest() != SHA:
        raise SystemExit("seasonal/spi&spei.py differs from the pinned version")
    src = raw.decode()
    lines = src.splitlines(keepends=True)
    defs = {n.name: n for n in ast.parse(src).body if isinstance(n, ast.FunctionDef)}
    parts = []
    for name in FUNCTIONS:
        n = defs[name]
        parts.append(f"# --- {name}: original lines {n.lineno}-{n.end_lineno}\n" + "".join(lines[n.lineno - 1:n.end_lineno]))
    return parts


if __name__ == "__main__":
    parts = extract(sys.argv[1])
    header = ('"""VENDORED, DO NOT EDIT: verbatim functions of IPCCH_shared_folder seasonal/spi&spei.py (sha256 ' + SHA + '),\n'
              'generated by tools/vendor_ipcch_seasonal_spi_spei.py. Not imported as a module: cloud.ipcch.spi_spei_seasonal\n'
              'executes this text in a fresh namespace with the original module globals bound explicitly."""\n\n')
    open(OUT, "w", newline="\n").write(header + "\n\n".join(parts))
    print(OUT, sum(p.count("\n") for p in parts), "lines")
