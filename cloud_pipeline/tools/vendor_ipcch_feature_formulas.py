"""Regenerate the vendored IPCCH feature formulas (task 10-29 R13/R32/R58/R59/R62/R65): the research modules that built the
final H2/H8/H14 matrices, kept verbatim so operational assembly uses the same arithmetic.

* cloud/ipcch/vendor/ipcch_months.py   = ipcch_alphaearth/months.py   (byte copy)
* cloud/ipcch/vendor/ipcch_compact.py  = ipcch_alphaearth/compact.py  (byte copy except its single
  ``from ipcch_alphaearth.months import month_ord`` line, redirected to the vendored months module)
* cloud/ipcch/vendor/ipcch_validity_feature_blocks.py = the history / national IDP / local IDP / aggregated-ACLED block
  functions and their constants of research_cloud/training/ipcch_validity_features.py (AST-extracted verbatim), after a
  labelled shim providing ``ae_modules()`` (the vendored compact module) and ``DataContractError``.

  python tools/vendor_ipcch_feature_formulas.py <IPCCHAlphaEarthExperiment/ipcch_alphaearth> <ipcch_validity_features.py>
"""
import ast
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
VENDOR = os.path.join(HERE, "..", "cloud", "ipcch", "vendor")
PINS = {"months.py": "4ffcb34f519ca91c90348ed3946e429b21a8348a9220ff4f4b515d066b8afbc9",
        "compact.py": "824233163023c796bc729389b3f6c6cc473ba56c7a1cb5509009c12940194c53",
        "ipcch_validity_features.py": "e56ccf418aca"}          # prefix of the trained features module (frozen 9aa9e54)
IMPORT_ORIGINAL = "from ipcch_alphaearth.months import month_ord\n"
IMPORT_VENDORED = "from cloud.ipcch.vendor.ipcch_months import month_ord\n"
VF_FUNCTIONS = ("history_bound", "history_block", "idp_block", "idp_local_arrays", "idp_local_block", "acled_lag_name",
                "acled_agg_arrays", "acled_agg_block")
VF_CONSTANTS = ("SCALE", "HISTORY_VALUES", "HISTORY_FEATURES", "IDP_LOCAL_VALUE", "IDP_LOCAL_FEATURES", "IDP_LOCAL_WINDOWS",
                "ACLED_AGG_GROUPS", "ACLED_AGG_TYPES", "ACLED_AGG_SOURCES", "ACLED_AGG_EVENT_SOURCES", "ACLED_AGG_LAG",
                "ORDINARY_STATS", "STRESS_STATS", "ACLED_AGG_FEATURES", "OLD_ACLED_FEATURES")
SHIM = '''"""VENDORED, DO NOT EDIT below the shim: history / IDP / aggregated-ACLED block functions of
research_cloud/training/ipcch_validity_features.py (sha256 {sha}), generated by tools/vendor_ipcch_feature_formulas.py."""
import numpy as np
import pandas as pd

from cloud.ipcch.vendor import ipcch_compact


# ---- shim (operational): the research module resolves its compact recipe through ae_modules()
class DataContractError(RuntimeError):
    """A source format or temporal contract check failed."""


def ae_modules():
    return ipcch_compact, None, None


# ---- verbatim research code
'''


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def main(ae_dir, vf_path):
    months, compact = os.path.join(ae_dir, "months.py"), os.path.join(ae_dir, "compact.py")
    for p, pin in ((months, PINS["months.py"]), (compact, PINS["compact.py"]), (vf_path, PINS["ipcch_validity_features.py"])):
        if not sha(p).startswith(pin):
            raise SystemExit(f"{p} differs from the pinned research version")
    open(os.path.join(VENDOR, "ipcch_months.py"), "wb").write(open(months, "rb").read())
    text = open(compact, "rb").read().decode()
    if text.count(IMPORT_ORIGINAL) != 1:
        raise SystemExit("compact.py import line not found exactly once")
    open(os.path.join(VENDOR, "ipcch_compact.py"), "w", newline="").write(text.replace(IMPORT_ORIGINAL, IMPORT_VENDORED))
    src = open(vf_path).read()
    lines = src.splitlines(keepends=True)
    tree = ast.parse(src)
    parts = []
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and getattr(node.targets[0], "id", None) in VF_CONSTANTS:
            parts.append("".join(lines[node.lineno - 1:node.end_lineno]))
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name in VF_FUNCTIONS:
            parts.append(f"# --- {node.name}: original lines {node.lineno}-{node.end_lineno}\n" + "".join(lines[node.lineno - 1:node.end_lineno]))
    names = {getattr(n.targets[0], "id", None) for n in tree.body if isinstance(n, ast.Assign) and len(n.targets) == 1}
    missing = [c for c in VF_CONSTANTS if c not in names] + [f for f in VF_FUNCTIONS if f not in {n.name for n in tree.body if isinstance(n, ast.FunctionDef)}]
    if missing:
        raise SystemExit(f"not found: {missing}")
    open(os.path.join(VENDOR, "ipcch_validity_feature_blocks.py"), "w", newline="\n").write(
        SHIM.format(sha=sha(vf_path)) + "\n".join(parts) + "\n")
    print("vendored", [sha(os.path.join(VENDOR, n))[:12] for n in ("ipcch_months.py", "ipcch_compact.py", "ipcch_validity_feature_blocks.py")])


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
