BASELINE = (1991, 2020)
REASONS = {"REASON_VALID": 0, "REASON_INPUT_MISSING": 1, "REASON_FIT_INVALID": 2, "REASON_OUTSIDE_SUPPORT": 3,
           "REASON_NUMERICAL": 4}
SEASONS = ("s1", "s2")
_TEXT = VENDOR.read_text()


def _namespace(all_months: pd.DatetimeIndex | None = None, index_months: pd.DatetimeIndex | None = None,
               n_admins: int | None = None, plan: pd.DataFrame | None = None) -> dict[str, Any]:
    ns: dict[str, Any] = {"np": np, "pd": pd, "special": special, "pycalendar": pycalendar,
                          "BASELINE_START_YEAR": BASELINE[0], "BASELINE_END_YEAR": BASELINE[1], "NORMAL_PROB_EPS": 1e-6,
                          "FULL_COVERAGE_TOLERANCE": 0.999999, "N_ADMINS": n_admins, "season_plan": plan,
                          "ALL_MONTHS": all_months, "INDEX_MONTHS": index_months, **REASONS}
    if all_months is not None:
        _axis(all_months, "all_months")
        _axis(index_months, "index_months")
        base = all_months[(all_months.year >= BASELINE[0]) & (all_months.year <= BASELINE[1])]
        if len(base) != 12 * (BASELINE[1] - BASELINE[0] + 1) or all_months[0] > pd.Timestamp(f"{BASELINE[0] - 1}-11-01"):
            raise ValueError("all_months must cover 1990-11 .. 2020-12 (complete strict 1991-2020 three-month baseline)")
        pos = all_months.get_indexer(index_months)
        if (pos < 0).any():
            raise ValueError("index_months must lie inside all_months")
        ns["INDEX_GLOBAL_POSITIONS"] = pos
    exec(compile(_TEXT, str(VENDOR), "exec"), ns)
    return ns


def _axis(months, label):
    if not isinstance(months, pd.DatetimeIndex) or len(months) == 0 or \
            not months.equals(pd.date_range(months[0], periods=len(months), freq="MS")):
        raise ValueError(f"{label} must be a non-empty contiguous month-start DatetimeIndex")


def monthly_indices(prcp: np.ndarray, et0: np.ndarray, all_months: pd.DatetimeIndex, index_months: pd.DatetimeIndex,
                    source: str) -> dict[str, Any]:
    """The original ``compute_spi03``/``compute_spei03`` on admin x all_months matrices (same areas, same row order)."""
    prcp = np.asarray(prcp, dtype=np.float64)
    et0 = np.asarray(et0, dtype=np.float64)
    if prcp.ndim != 2 or prcp.shape != et0.shape or prcp.shape[1] != len(all_months):
        raise ValueError(f"P {prcp.shape} and ET0 {et0.shape} must be identical (areas, {len(all_months)} months)")
    ns = _namespace(all_months, index_months, prcp.shape[0])
    spi, spi_reason, spi_diag = ns["compute_spi03"](prcp, source)
    spei, spei_reason, spei_diag = ns["compute_spei03"](prcp, et0, source)
    return {"spi": spi, "spi_reason": spi_reason, "spei": spei, "spei_reason": spei_reason,
            "diagnostics": pd.concat([spi_diag, spei_diag], ignore_index=True)}


def windows_from_calendar(calendar: pd.DataFrame, season_years) -> pd.DataFrame:
    """Season windows from per-admin calendar properties (``{s}_calendar_valid, _cross_year, _sos_month, _sos_day,
    _eos_month, _eos_day``), the original plan loop's first part: start = exact_date(Y - cross, sos), end inclusive =
    exact_date(Y, eos); invalid when a date is invalid or end <= start."""
    ns = _namespace()
    truthy, int_or_none, exact_date = ns["truthy"], ns["int_or_none"], ns["exact_date"]
    rows = []
    for _, admin in calendar.iterrows():
        for season_year in season_years:
            for season in SEASONS:
                valid = truthy(admin.get(f"{season}_calendar_valid"))
                cross = 1 if truthy(admin.get(f"{season}_cross_year")) else 0
                sm, sd, em, ed = (int_or_none(admin.get(f"{season}_{k}")) for k in ("sos_month", "sos_day", "eos_month", "eos_day"))
                start = end_exclusive = None
                if valid and None not in {sm, sd, em, ed}:
                    start = exact_date(season_year - cross, sm, sd)
                    end_inclusive = exact_date(season_year, em, ed)
                    if start is None or end_inclusive is None:
                        valid = False
                    else:
                        end_exclusive = end_inclusive + pd.Timedelta(days=1)
                        if end_exclusive <= start:
                            valid = False
                elif valid:      # the original would fail on this row (start None); never silently invalidate
                    raise ValueError(f"{admin['admin_code']} {season}: valid calendar with missing month/day")
                rows.append({"admin_code": str(admin["admin_code"]), "season_year": int(season_year), "season": season,
                             "gs_calendar_valid": int(valid),
                             "gs_start_date": start.strftime("%Y-%m-%d") if valid else None,
                             "gs_end_date_exclusive": end_exclusive.strftime("%Y-%m-%d") if valid else None})
    return pd.DataFrame(rows)


def season_plan(windows: pd.DataFrame, index_months: pd.DatetimeIndex, admin_order) -> pd.DataFrame:
    """The original exact season plan (month positions in ``index_months`` and calendar overlap days) for windows
    (admin_code, season_year, season, gs_calendar_valid, gs_start_date, gs_end_date_exclusive); rows of invalid
    calendars carry no positions. ``admin_order`` gives the matrix row of each admin_code."""
    _axis(index_months, "index_months")
    lookup = {d.year * 100 + d.month: i for i, d in enumerate(index_months)}
    row_of = {str(a): i for i, a in enumerate(admin_order)}
    out = []
    for w in windows.itertuples(index=False):
        valid = int(w.gs_calendar_valid) == 1
        positions, overlap, duration = [], [], np.nan
        if valid:
            start, end_exclusive = pd.Timestamp(w.gs_start_date), pd.Timestamp(w.gs_end_date_exclusive)
            duration = int((end_exclusive - start).days)
            p = start.to_period("M")
            last_period = (end_exclusive - pd.Timedelta(days=1)).to_period("M")
            while p <= last_period:
                ms, me = p.start_time, (p + 1).start_time
                days = int((min(end_exclusive, me) - max(start, ms)).days)
                if days > 0:
                    code = p.year * 100 + p.month
                    if code not in lookup:
                        raise RuntimeError(f"Required month {code} unavailable")
                    positions.append(lookup[code])
                    overlap.append(days)
                p += 1
            if sum(overlap) != duration:
                raise AssertionError((w.admin_code, w.season_year, w.season, duration, sum(overlap)))
        if str(w.admin_code) not in row_of:
            raise ValueError(f"season window for an admin outside the matrix rows: {w.admin_code}")
        out.append({"admin_code": str(w.admin_code), "season_year": int(w.season_year), "season": w.season,
                    "gs_calendar_valid": int(valid), "gs_duration_recalculated_days": duration,
                    "gs_start_date": w.gs_start_date if valid else None, "gs_end_date_exclusive": w.gs_end_date_exclusive if valid else None,
                    "_admin_position": row_of[str(w.admin_code)], "_month_positions": positions, "_overlap_days": overlap})
    return pd.DataFrame(out)


def aggregate(monthly: np.ndarray, monthly_reason: np.ndarray, plan: pd.DataFrame, metric_name: str) -> pd.DataFrame:
    """The original ``aggregate_gs`` over ``plan`` (rows aligned with the plan)."""
    return _namespace(plan=plan.reset_index(drop=True))["aggregate_gs"](monthly, monthly_reason, metric_name)


