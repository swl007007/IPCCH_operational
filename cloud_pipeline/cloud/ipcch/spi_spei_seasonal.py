"""Seasonal SPI-3 / SPEI-3 of the shared-folder ``seasonal/spi&spei.py`` (sha256 fbc55979...; task 10-29 R1/R33/R34/R40).

This is NOT the monthly script's computation (``spi_spei``): the seasonal script fits SPEI with its own
``fit_glo_ubpwm`` (unbiased PWMs, k = -tau3) and ``glo_probability_strict``, keeps per-month reason codes, and aggregates
monthly indices to a growing season by exact calendar-overlap days with a full-coverage requirement (``aggregate_gs``).

The original functions are vendored verbatim (``vendor/seasonal_spi_spei_v3.py``, generated by
``tools/vendor_ipcch_seasonal_spi_spei.py``) and executed in a fresh namespace per call with the original module globals
bound explicitly (month axes, index positions, admin count, baseline years, epsilon, coverage tolerance, reason codes, the
season plan). The module-level "BUILD EXACT SEASON PLAN" loop of the original is ported as ``season_plan`` /
``windows_from_calendar`` (same exact_date rule: only Feb 29 -> Feb 28 in a non-leap year; other invalid days make the
calendar invalid).
"""

