VENDOR = Path(__file__).with_name("vendor") / "seasonal_spi_spei_v3.py"
SCRIPT_SHA256 = "fbc559792896f5dc251aceb1ad83926c0cbdf2107c713aeb14701359dea690a7"
# The original labels its SPEI "SPEI_UBPWM_GLO_STRICT_SUPPORT_V3" like the monthly script, but the fit differs; the
# operational identifier names the script and function so the two are never conflated (R40).
SPEI_FIT = "SPEI_UBPWM_GLO_STRICT_SUPPORT_V3@seasonal/spi&spei.py:fit_glo_ubpwm+glo_probability_strict"   # = climate.SPEI_FIT_SEASONAL
SPI_FIT = "GAMMA_ZERO_CORRECTED@seasonal/spi&spei.py:compute_spi03"
