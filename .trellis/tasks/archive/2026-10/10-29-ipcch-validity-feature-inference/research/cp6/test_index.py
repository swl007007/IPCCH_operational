"""CP6: index every test of the task-relevant suites with its docstring's first line and the requirement ids it names
(module docstring ids apply to every test of the module). Output: test-index.json + test-index.md (this directory).
Run: python3 test_index.py"""

import ast
import json
import re
from pathlib import Path

OP = Path(__file__).resolve().parents[5] / "cloud_pipeline"
SUITES = sorted([*OP.glob("tests/cloud/test_*.py"), OP / "tests/test_operator_release.py", OP / "tests/test_operator_cli.py"])
IDS = re.compile(r"\b(R\d{1,2}|FCC\d{1,2}|AC\d{1,2}|D[1-3])\b")


def ids(text):
    return sorted(set(IDS.findall(text or "")), key=lambda s: (re.sub(r"\d", "", s), int(re.sub(r"\D", "", s))))


index = {}
for path in SUITES:
    tree = ast.parse(path.read_text())
    module_ids = ids(ast.get_docstring(tree))
    tests = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith("test_"):
            doc = ast.get_docstring(node) or ""
            tests.append({"name": node.name, "line": node.lineno, "doc": doc.split("\n")[0][:160], "ids": ids(doc)})
    index[str(path.relative_to(OP))] = {"module_ids": module_ids, "tests": sorted(tests, key=lambda t: t["line"])}
Path(__file__).with_name("test-index.json").write_text(json.dumps(index, indent=1, sort_keys=True) + "\n")
lines = ["# CP6 test index (generated by test_index.py)", "",
         f"{sum(len(v['tests']) for v in index.values())} test functions in {len(index)} suites "
         "(parametrized cases counted once).", ""]
for f, v in index.items():
    lines.append(f"## {f}  ({len(v['tests'])} tests; module ids: {', '.join(v['module_ids']) or '-'})")
    for t in v["tests"]:
        lines.append(f"- `{t['name']}` :{t['line']} {('[' + ', '.join(t['ids']) + '] ') if t['ids'] else ''}{t['doc']}")
    lines.append("")
Path(__file__).with_name("test-index.md").write_text("\n".join(lines))
print(lines[2])
